-- =============================================================================
-- V6__demo_roster.sql — 시연용 고객 명단
--
-- V5의 합성 명단에 더해 시연에서 실제로 넣어볼 이름을 적재한다.
-- **규칙도 코드도 건드리지 않는다.** 명단은 데이터이고 규칙은 컬럼명만 참조한다 —
-- 조직이 바뀔 때 필요한 작업이 "코드 수정"이 아니라 "명단 적재"라는 것이 V5의 요점이다.
--
-- given_name_detectable
--   이름을 비우는 대신 플래그를 둔다. 이름은 사실이고 단독 탐지 여부는 정책이라,
--   `박재현`의 이름이 `재현`이라는 사실을 지울 이유가 없다.
--
--   false인 행은 이름 단독 탐지(PII-CUST-08)에서 빠진다. 성을 뗀 부분이 한 글자이거나
--   일반 명사와 겹치는 경우다 — `재현`은 재현성, `인체`는 人體, `대령`은 군 계급,
--   `다운`은 다운로드, `회중`은 회중시계. 그대로 두면 검토 대기가 소음으로 찬다.
--   전체 이름 마스킹(PII-CUST-07)은 플래그와 무관하게 그대로다.
-- =============================================================================

ALTER TABLE customer ADD COLUMN given_name_detectable BOOLEAN NOT NULL DEFAULT true;

COMMENT ON COLUMN customer.given_name_detectable IS
    '이름 단독 탐지 대상 여부. 일반 명사와 겹치는 이름을 false로 둔다. 전체 이름 마스킹과는 무관';

