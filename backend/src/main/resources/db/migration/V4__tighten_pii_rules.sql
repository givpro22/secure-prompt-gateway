-- =============================================================================
-- V4__tighten_pii_rules.sql — 마스킹 규칙 정밀화
--
-- 방향은 둘이다. **경계를 조여 오탐을 없애고**, 빠져 있던 식별자를 채운다.
--
-- 왜 오탐을 줄이는가
--   재현율만 올리면 오탐이 늘고, 오탐이 늘면 사용자가 게이트웨이를 우회할 길을 찾는다.
--   그때 통제율은 0이 된다. 차단율 100%인 게이트웨이가 실제 보안 수준으로는 최악이 되는
--   역설이며, 정밀도를 함께 잡지 않으면 이 설계 전체가 무의미해진다.
--
-- 공통 기법
--   `\b` 대신 `(?<![0-9])` / `(?![0-9])`를 쓴다. 한글 문장에서 `\b`는 한글과 숫자 사이를
--   경계로 보기 때문에 의도가 드러나지 않는다. "앞뒤에 숫자가 오면 안 된다"를 그대로 적는다.
--
-- 검증
--   후보 패턴 6종을 Java 정규식 엔진으로 양성 15 / 음성 12 케이스에 돌려 전건 확인했다.
--   Python `re`와 lookbehind 규칙이 달라 반드시 Java에서 확인해야 한다.
--   데모 Case A의 주민번호 span [73,87]과 Case D의 전화번호 span [8,21]은 그대로다.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. 기존 4종 경계 조이기
-- -----------------------------------------------------------------------------

-- 주민번호 — 월(01-12)·일(01-31) 범위를 정규식에 넣는다.
-- 기존 `\d{6}-?[1-4]\d{6}`은 `991301-1234567`(13월)·`990132-1234567`(32일)을 그대로 잡았고,
-- 앞에 숫자가 붙은 `1900101-1234567`에서도 뒷부분을 부분 매칭했다.
UPDATE policy_rule SET
    pattern = '(?<![0-9])\d{2}(?:0[1-9]|1[0-2])(?:0[1-9]|[12][0-9]|3[01])-?[1-4]\d{6}(?![0-9])',
    description = '주민등록번호. 월·일 범위와 숫자 경계까지 검사'
 WHERE code = 'PII-RRN-01';

-- 카드번호 — 구분자 일관성을 강제한다. 하이픈이 전부 있거나 전부 없거나 둘 중 하나다.
-- 기존 `\b(\d{4}-?){3}\d{4}\b`는 `1234-5678-90123456` 같은 혼용을 통과시켰고,
-- 반복되는 캡처 그룹이라 캡처가 무의미했다(픽스처 서버는 이미 비캡처로 써 있어 문자열이 어긋나 있었다).
UPDATE policy_rule SET
    pattern = '(?<![0-9])(?:\d{4}-\d{4}-\d{4}-\d{4}|\d{16})(?![0-9])',
    description = '신용카드 번호. 구분자 일관성과 숫자 경계까지 검사'
 WHERE code = 'PII-CARD-02';

-- 휴대전화 — 역시 구분자 일관성. 기존 `01[016789]-?\d{3,4}-?\d{4}`는
-- `0101234-5678`처럼 한쪽만 붙은 반쪽짜리도 잡았다.
UPDATE policy_rule SET
    pattern = '(?<![0-9])01[016789](?:-\d{3,4}-\d{4}|\d{7,8})(?![0-9])',
    description = '휴대전화 번호. 구분자 일관성과 숫자 경계까지 검사'
 WHERE code = 'PII-PHONE-03';

-- 이메일 — TLD를 알파벳 2자 이상으로 못 박는다.
-- 기존 `[\w.+-]+@[\w-]+\.[\w.]+`는 TLD가 `[\w.]+`라 숫자도 통과했고,
-- 그래서 Case A의 `p%40ss@10.0.3.21`이 이메일로 오탐됐다.
--
-- **이 변경으로 Case A의 원시 매칭이 4건에서 3건이 된다** (기획서 0.5 D11 갱신).
-- 중첩 억제 시연은 그대로다 — SEC-PRIVIP-03이 여전히 SEC-DBURL-02 구간에 포함되어
-- finding은 2건이다. 억제로 가려지던 오탐이 애초에 발생하지 않게 된 것이 이번 변경이다.
UPDATE policy_rule SET
    pattern = '[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}',
    description = '이메일 주소. 최상위 도메인은 알파벳 2자 이상'
 WHERE code = 'PII-EMAIL-04';

-- -----------------------------------------------------------------------------
-- 2. 신규 2종
--
--    여권번호(`[MSRO]\d{8}`)는 넣지 않았다. 문맥 없이는 사내 자산번호·주문번호와 충돌해
--    오탐이 이득을 넘어선다. 문맥 가중치는 이번 범위 밖이다 (기획서 17장으로 이관).
-- -----------------------------------------------------------------------------

-- 사업자등록번호 — 3-2-5 형식이 고유해서 문맥 없이도 오탐이 적다.
-- 법인 식별자라 개인정보가 아니므로 obligation은 INTERNAL이다.
INSERT INTO policy_rule
    (rule_id, policy_id, code, rule_type, pattern, action, mask_label, severity, obligation, source, description) VALUES
    (11, 1, 'PII-BIZNO-05', 'REGEX', '(?<![0-9])\d{3}-\d{2}-\d{5}(?![0-9])',
        'MASK', '[사업자번호]', 'MEDIUM', 'INTERNAL', '정보보안규정 4.4', '사업자등록번호 형식 탐지'),

-- 계좌번호 — **문맥을 요구한다.** 은행마다 자릿수가 달라 형식만으로는 버전 번호·주문 번호와
-- 구분되지 않는다. 앞 8자 안에 계좌·입금·송금·이체가 있을 때만 잡는다.
-- lookbehind는 마스킹 구간에 포함되지 않으므로 '계좌'라는 단어는 본문에 그대로 남는다.
    (12, 1, 'PII-ACCOUNT-06', 'REGEX',
        '(?<=계좌[^\n]{0,8}|입금[^\n]{0,8}|송금[^\n]{0,8}|이체[^\n]{0,8})(?<![0-9])\d{2,6}-\d{2,6}-\d{2,8}(?![0-9])',
        'MASK', '[계좌번호]', 'HIGH', 'LEGAL', '개인정보보호법', '계좌번호. 금융 문맥이 있을 때만 탐지');

-- P-PII의 규칙이 4종에서 6종이 되었다. 정책 버전을 올려 판정 스냅샷이 시점을 구분하게 한다.
-- 이 값을 올리지 않으면 어제의 판정과 오늘의 판정이 같은 근거를 가리키게 되어 감사가 거짓이 된다.
--
-- `version + 1`이 아니라 명시값을 쓴다. 상대 증가는 마이그레이션 시점의 DB 상태에 결과가
-- 달라지는데, 계약 확정본·api-spec·ai-prompt·픽스처가 전부 `P-PII:4`를 예시로 박아 두었다.
-- 시드 값은 어느 DB에서 돌리든 같아야 한다 — V3의 PK 충돌(PR #2)이 같은 뿌리의 문제였다.
UPDATE policy SET version = 4 WHERE code = 'P-PII';

SELECT setval(pg_get_serial_sequence('policy_rule', 'rule_id'), (SELECT max(rule_id) FROM policy_rule));
